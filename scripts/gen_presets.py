#!/usr/bin/env python3
"""docs/progressions.json から chord_midi_web/src/presets.rs を生成する。

使い方:
    just gen-presets  (= python3 scripts/gen_presets.py)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "docs" / "progressions.json"
RS_PATH = ROOT / "chord_midi_web" / "src" / "presets.rs"


def rust_str(s):
    """Rust の文字列リテラルにする。改行はエスケープする"""
    escaped = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def main():
    data = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    lines = [
        "// @generated by scripts/gen_presets.py from docs/progressions.json",
        "// 手で編集しない。`just gen-presets` で再生成する。",
        "",
        "/// 進行プリセット1件",
        "pub struct Preset {",
        "    /// ボタンに出す名前",
        "    pub name: &'static str,",
        "    /// ボタンに出す短いディグリー表記",
        "    pub degrees: &'static str,",
        "    /// 入力欄に挿入する rechord 記法の進行",
        "    pub progression: &'static str,",
        "}",
        "",
        "pub const PRESETS: &[Preset] = &[",
    ]
    for preset in data["presets"]:
        lines.append("    Preset {")
        lines.append(f'        name: {rust_str(preset["name"])},')
        lines.append(f'        degrees: {rust_str(preset["degrees"])},')
        lines.append(f'        progression: {rust_str(preset["progression"])},')
        lines.append("    },")
    lines.append("];")
    RS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(data['presets'])} presets")


if __name__ == "__main__":
    main()
